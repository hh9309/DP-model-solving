export function getHeuristicReport(
  problemType: string,
  params: any,
  dpTable: number[][],
  backtrackPath: any[]
): string {
  const resultStr = backtrackPath && backtrackPath.length > 0 
    ? `最优决策路径价值/成本为 **${dpTable && dpTable.length > 0 ? dpTable[dpTable.length - 1][dpTable[0].length - 1] ?? '已算' : '计算完成'}**`
    : '状态表尚在演进填充中';

  if (problemType === 'knapsack') {
    const weights = params.weights || [2, 3, 4, 5];
    const values = params.values || [3, 4, 5, 6];
    const capacity = params.capacity || 8;
    return `### 1. 01背包问题：状态空间与剪枝分析
* **状态规模分析**：当前物品数 $N = ${weights.length}$，背包容量 $W = ${capacity}$，决策状态矩阵大小为 $(N+1) \\times (W+1) = ${(weights.length + 1) * (capacity + 1)}$。
* **常数优化与剪枝**：
  - **重量超限剪枝**：在填表迭代时，若当前物品重量 $w_i > j$，直接继承上方单元格 $dp[i-1][j]$，避免不必要的子问题决策计算。
  - **剩余价值剪枝**：在分支限界或记忆化实现中，若当前已累积价值加上后续剩余所有物品的总价值仍小于当前已找到的最佳收益，可提早回溯。

### 2. 边界条件与特殊警告
* **极端输入审查**：当前最大容量为 ${capacity}。若容量为 0，最优解将退化为 0；若物品包含负重量或负价值，会破坏动态规划的“无后效性”假设，需采用平移变换或改用通用图搜索。
* **极端测试预防**：如果遇到超大容量背包（例如 $W = 10^9$），直接建立二维表会导致内存溢出（MLE）。此时应该利用稀疏性更新或采用按价值状态 $dp[v]$ 的倒置动态规划。

### 3. 状态依赖树与空间压缩路径
* **递推依赖方向**：每个单元格 $dp[i][j]$ 仅依赖上一行正上方的格子 $dp[i-1][j]$ 和左上方的格子 $dp[i-1][j-w_i]$。
* **一维一倍空间优化**：可以将空间复杂度从 $O(N \\times W)$ 压缩至 $O(W)$。为了保证每个物品只被选择一次，内层容量循环**必须使用逆序迭代**（从 $W$ 递减到 $w_i$）：
  \`\`\`python
  dp = [0] * (W + 1)
  for i in range(N):
      for j in range(W, weights[i] - 1, -1):
          dp[j] = max(dp[j], dp[j - weights[i]] + values[i])
  \`\`\`
  ${resultStr}。`;
  }

  if (problemType === 'shortest_path') {
    const grid = params.grid || [[1]];
    const r = grid.length;
    const c = grid[0].length;
    return `### 1. 最短路径规划：状态空间与剪枝分析
* **状态规模分析**：行数 $R = ${r}$，列数 $C = ${c}$。状态矩阵规模为 $R \\times C = ${r * c}$。
* **路径剪枝手段**：
  - **死路障碍物规避**：若某网格成本配置为极大值（如 99），状态转移时可跳过该格，降低不连通格子的常数级扫描消耗。
  - **A* 估价启发剪枝**：如果与曼哈顿距离估价结合，可以大幅度减少动态规划在偏离最优主路径方向上的状态展开。

### 2. 边界条件与特殊警告
* **边界安全验证**：第一行和第一列格子只能从左侧或上方单向转移而来，无多路径决策。
* **负环异常警告**：本演进模型假定为无后向环的 DAG 网格。如果存在任意负权路径或后向负反馈环路，单纯的递推动态规划将会失效，系统可能因无限后退依赖而死锁，此时必须调用 Bellman-Ford 或 SPFA 算法。

### 3. 状态依赖树与空间压缩路径
* **转移方程**：$dp[i][j] = \\text{grid}[i][j] + \\min(dp[i-1][j], dp[i][j-1])$。
* **一维空间滚动压缩**：
  计算当前行仅依赖于“当前行左侧格”和“上一行上方格”。因此可以压缩为一维数组 \`dp[j]\`：
  \`\`\`python
  dp = [infinity] * C
  dp[0] = grid[0][0]
  # 填充第一行...
  for i in range(1, R):
      dp[0] += grid[i][0] # 更新第一列
      for j in range(1, C):
          dp[j] = grid[i][j] + min(dp[j], dp[j-1])
  \`\`\`
  ${resultStr}。`;
  }

  if (problemType === 'equipment') {
    const years = params.years || 4;
    return `### 1. 设备更新决策：状态空间与剪枝分析
* **状态规模分析**：设备役龄范围为 $1 \\sim 4$ 岁，规划期数 $T = ${years}$，状态表规模为 $(T+1) \\times 4 = ${(years + 1) * 4}$。
* **常数剪枝空间**：
  - **超龄直接报废剪枝**：役龄达到最大年龄阈值（如 4 岁）时，决策树分支剪去“继续维持”选项，强制进行“置换新设备”，减少无效迭代。

### 2. 边界条件与特殊警告
* **边界完整性**：第 0 年属于启动期初，役龄仅为 1 岁。
* **断崖价值折旧警告**：如果残值曲线包含负数（如高昂的废弃拆除处理费），或者运行维护费随年龄呈非线性指数暴涨，会导致早期的置换操作极为剧烈，需密切校验第一年和最后一年的残值系数。

### 3. 状态依赖与决策树
* **逆向动态规划思想**：
  设备更新通常从最后一期 $T$ 开始倒推，计算每一阶段保留和置换的损益极值。
  一维滚动压缩在这里是不适用的，因为多阶段决策的生存方程具有跨越多个役龄周期的跨步依赖，必须保留完整的役龄/年份依赖矩阵以完成回溯。
  ${resultStr}。`;
  }

  if (problemType === 'production_inventory') {
    const periods = params.periods || 4;
    const demands = params.demands || [2, 3, 2, 4];
    return `### 1. 生产与库存控制问题：状态空间与剪枝分析
* **状态规模分析**：规划周期 $T = ${periods}$，最大允许库存容量为 ${params.maxInventory}。状态空间维度为周期数与库存状态的乘积：$(T+1) \\times (S_{\\max}+1)$。
* **可行决策空间剪枝**：
  - **最大产出限制**：在任一阶段，生产数量 $x_t$ 的上限由最大库存限度及后续总需求限制双向制约，不应计算超过此合理界限的多余决策。
  - **零库存提前中止**：期末库存必须归零，所有导致期末库存不为零的多余状态可置为无效。

### 2. 边界条件与特殊警告
* **安全库存警戒**：若输入需求 $D_t$ 大于当前最大库存与最大生产量之和，系统将出现“供给缺口”死锁（无解）。此时标准的 DP 单元格应填入极大值 $999999$ 表示不可达。
* **非线性生产成本**：启动费用具有高度台阶性。当启动生产固定成本 $K$ 极高时，决策将表现出强烈的“批次合一”特征。

### 3. 状态依赖与空间滚动
* **决策方程**：
  $dp[t][s] = \\min_{x} \\left\\{ \\text{Setup}(x) + \\text{UnitCost} \\cdot x + \\text{HoldingCost} \\cdot (s + x - D_t) + dp[t-1][s + x - D_t] \\right\\}$。
  ${resultStr}。`;
  }

  if (problemType === 'markov_portfolio') {
    const budget = params.budget || 4;
    const projects = params.projects || 3;
    return `### 1. 马尔可夫决策与投资组合：状态空间与剪枝分析
* **状态规模分析**：分配项目数 $N = ${projects}$，可用总配额 $B = ${budget}$。状态转移矩阵大小为 $(N+1) \\times (B+1)$。
* **剪枝与边际效应优化**：
  - **配额超限提前截止**：分配给项目的预算之和不能超过 $B$。在每一层决策搜索时，分支上限为当前剩余预算，可减免无效状态展开。
  - **边际收益递减剪枝**：当某项目分配更多预算但边际收益不增或递减时，大额配额分支可直接忽略。

### 2. 边界条件与风险警告
* **预算约束**：预算为 0 时最优收益为 0。
* **高风险失效警告**：如果某项目存在由于失败导致的严重惩罚（如负收益），需要调整状态空间以记录转移概率下的期望。当前模型的确定性 DP 假设回报表已知。

### 3. 状态依赖与空间优化
* **状态更新模式**：
  自底向上对项目逐一添加决策，属于背包变形的多阶段决策问题。可以应用一维滚动数组 \`dp[j]\` 从大到小进行压缩，消除项目维度：
  \`\`\`python
  dp = [0] * (Budget + 1)
  for i in range(Projects):
      for j in range(Budget, -1, -1):
          dp[j] = max(dp[j-k] + return[i][k] for k in range(j+1))
  \`\`\`
  ${resultStr}。`;
  }

  if (problemType === 'resource_allocation') {
    const projects = params.projects || 3;
    const totalResource = params.totalResource || 4;
    return `### 1. 资源分配问题 (Resource Allocation) 状态空间与剪枝分析
* **状态规模分析**：项目数 $N = ${projects}$，总可用资源 $M = ${totalResource}$。DP 状态空间由 $(i, j)$ 组成，其中 $i$ 表示前 $i$ 个项目，$j$ 表示已分配的累计资源。状态表总大小为 $N \\times (M + 1) = ${projects * (totalResource + 1)}$。
* **剪枝可能性**：
  - **资源配额下限剪枝**：如果一个项目必须有最小启动资源（如 threshold $k > 0$），那么当分配的资源小于该阈值时可以直接不予考虑，或者立即归为 0 收益分支。
  - **单步无益剪枝**：若追加分配给某项目的资源不能带来比已有最佳收益更高的增量，可停止递增分配。

### 2. 边界与特殊警告
* **状态表初始边界**：
  初始状态为 $dp[0][j] = 0$（不分配任何项目时，所有资源的累积收益初始均为 0），其余阶段在计算时依次向上迭代。
* **越界与未定义风险**：若分配给某项目的收益表长度小于 $M+1$，需要进行越界保护（超出部分视作最后一位的收益），否则会导致索引越界或数据未定义。
* **非单调收益风险**：部分项目可能存在资源边际效应递减、甚至过度投资导致负收益（如人员冗余），算法需要能准确识别并避开非单调峰值。

### 3. 状态转移递推与空间要求
* **状态转移方程**：
  $dp[i][j] = \\max_{0 \\le k \\le j} \\left\\{ dp[i-1][j-k] + \\text{returns}[i-1][k] \\right\\}$。
  属于典型的分阶段资源分配决策，可以通过一维滚动数组 \`dp[j]\` 进行空间压缩，注意第二重循环需逆序（从 $M$ 递减到 $0$）以防止同一项目被重复分配。
  ${resultStr}。`;
  }

  return `### 智能决策分析报告
* **问题类别**：${problemType}
* **状态评估**：分析已完成。
${resultStr}。`;
}
